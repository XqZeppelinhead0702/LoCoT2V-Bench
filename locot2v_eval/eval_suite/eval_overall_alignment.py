import os
import sys
import json
import argparse
import torch
import re
import traceback

from transformers import Qwen3VLForConditionalGeneration, AutoProcessor
from tqdm import tqdm

ROOT_ABS_PATH = os.path.abspath(os.path.join(os.path.dirname(__file__), "../.."))
sys.path.insert(0, ROOT_ABS_PATH)


OVA_EVAL_PROMPT="""You are good at understanding the content of videos and serving as an objective evaluator of video-text alignment.

Evaluate how well the given video matches the provided description only based on what is visible in the video.

Evaluate the following aspects:
1. Characters (appearance, roles, number)
2. Setting and environment
3. Key actions and events
4. Interactions and outcomes

For each aspect, consider whether it is:
- Fully matched
- Partially matched
- Not matched

Then give an overall score from 0 to 100 based on the overall alignment. The score should be deterministic and consistent across repeated evaluations of the same input.

Scoring rules:
- Strong alignment across all aspects: 85–100
- Good alignment with minor issues: 65–84
- Mixed or incomplete alignment: 40–64
- Weak alignment: 10–39
- No clear alignment: 0–9

You should only respond with an integer ranging from 0 to 100 as your scoring result without any other irrelevant content.

Now here is the provided description:
{description_text}
"""

class OvaScorer:
    """
    Given path of certain video generated by AI, OvaScorer is supposed to calculate 
    overall video2text alignment score to its corresponding prompt.
    
    We use Qwen3-VL-8B-Instruct as MLLM for judgement.
    """
    def __init__(self, mllm_path: str, upper_bound=100):
        self.load_mllm(mllm_path)
        self.upper_bound = upper_bound
        
    def get_ova_score(self, video_path: str, description_text: str):
        eval_prompt = OVA_EVAL_PROMPT.format(description_text=description_text)
        ova_score = self.get_mllm_response(prompt=eval_prompt, video_path=video_path)
        res = eval(ova_score) / self.upper_bound
        return res
        
    def get_mllm_response(self, prompt: str, image_path: str | None=None, video_path: str | None=None, max_new_tokens: int=1024):
        messages = [
            {
                "role": "user",
                "content": []
            }
        ]
        if image_path is not None:
            messages[0]["content"].append({"type": "image", "image": image_path})
        if video_path is not None:
            messages[0]["content"].append({"type": "video", "video": video_path})
        messages[0]["content"].append({"type": "text", "text": prompt})
        inputs = self.mllm_processor.apply_chat_template(
            messages,
            tokenize=True,
            add_generation_prompt=True,
            return_dict=True,
            return_tensors="pt"
        )
        inputs = inputs.to(self.mllm.device)
        # Inference: Generation of the output
        generated_ids = self.mllm.generate(**inputs, max_new_tokens=max_new_tokens)
        generated_ids_trimmed = [
            out_ids[len(in_ids) :] for in_ids, out_ids in zip(inputs.input_ids, generated_ids)
        ]
        output_text = self.mllm_processor.batch_decode(
            generated_ids_trimmed, skip_special_tokens=True, clean_up_tokenization_spaces=False
        )[0]
        return output_text

    def load_mllm(self, model_name_or_path: str):
        self.mllm = Qwen3VLForConditionalGeneration.from_pretrained(
            model_name_or_path,
            dtype=torch.bfloat16,
            attn_implementation="flash_attention_2",
            device_map="auto",
        )
        self.mllm_processor = AutoProcessor.from_pretrained(model_name_or_path)
        

def get_args():
    parser = argparse.ArgumentParser(description="Overall video2text alignment evaluation launched.")
    parser.add_argument("--eval_data", type=str, required=True, help="Path to the list file of videos to be evaluated.")
    parser.add_argument("--mllm_path", type=str, default=f"{ROOT_ABS_PATH}/ckpts/Qwen3-VL-8B-Instruct", help="Path to save the MLLM used for video scoring task.")
    parser.add_argument("--src_path", type=str, default=f"{ROOT_ABS_PATH}/data/prompt.json", help="Path to source the prompt metadata.")
    parser.add_argument("--result_path", type=str, required=True, help="Path to save the evaluation results.")
    args = parser.parse_args()
    return args


def main(args):
    assert os.path.exists(args.eval_data), f"Failed to find corresponding file of {args.eval_data}, please carefully check your path again!"
    results = {
        "overall_score": 0.0,
        "sample_scores": {}
    }
    total_score = 0.0
    ova_scorer = OvaScorer(mllm_path=args.mllm_path)
    with open(args.eval_data, 'r') as f1, open(args.result_path, 'w') as f2, open(args.src_path, 'r') as f3:
        test_samples = json.load(f1)
        prompt_data = json.load(f3)
        for test_id, video_path in tqdm(test_samples.items()):
            theme_name = "_".join(test_id.split('_')[:-1])
            description_text = prompt_data[theme_name][test_id]["purified_prompt"]
            try:
                sample_score = ova_scorer.get_ova_score(video_path, description_text)
                results["sample_scores"][test_id] = sample_score
                total_score += sample_score
            except Exception as e:
                print(f"{str(e)} encountered when processing {video_path}! Ignoring this video...")
                traceback.print_exc()
                results["sample_scores"][test_id] = -1.0
        total_score = round(total_score / len(test_samples), 4)
        results["overall_score"] = total_score
        json.dump(results, f2, indent=4, ensure_ascii=False)   
        print(f"Average overall alignment score is: {total_score: .4f}")


if __name__ == "__main__":
    args = get_args()
    main(args)