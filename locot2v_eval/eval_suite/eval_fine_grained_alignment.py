import os
import sys
import json
import argparse
import torch
import traceback

from transformers import Qwen3VLForConditionalGeneration, AutoProcessor
from tqdm import tqdm
from typing import List

ROOT_ABS_PATH = os.path.abspath(os.path.join(os.path.dirname(__file__), '../..'))
sys.path.insert(0, ROOT_ABS_PATH)

# Suffix appended to every question to force the MLLM to answer only "Yes" or "No".
CONTROL_SUFFIX = " Only answer \"Yes\" or \"No\"."
device = 'cuda' if torch.cuda.is_available() else 'cpu'


class FgaScorer:
    """
    Given path of certain video generated by AI, FgaScorer is supposed to calculate 
    fine-grained video2text alignment score to its corresponding prompt.
    
    We use Qwen3-VL-8B-Instruct as MLLM for judgement.
    """
    def __init__(self, mllm_path: str):
        # Load the Qwen3-VL model and its processor.
        self.load_mllm(mllm_path)
    
    def get_fga_score(self, video_path: str, fga_questions: dict):
        scene_score = 0
        scene_existence_score = 0
        # --- Character facet: appearance anchors + actions ---
        # character related
        character_attr_score = 0
        character_action_score = 0
        # --- Background facet: background type + conformity to descriptions ---
        # background related
        background_type_score = 0
        background_conformity_score = 0
        # --- Camera movement facet ---
        # camera movement related
        camera_movement_score = 0
        character_anchor_questions = fga_questions["character_anchor_questions"]
        # Iterate over all scenes. First verify scene existence, then score character, background and camera-movement facets.
        for scene_question in fga_questions["scene_questions"]:
            # Ask whether the current scene appears in the generated video.
            scene_exist_context = [
                {
                    "role": "user",
                    "content": [
                        {"type": "video", "video": video_path},
                        {"type": "text", "text": scene_question["scene_existence"] + CONTROL_SUFFIX}
                    ]
                } 
            ]
            scene_exist_ans = self.get_mllm_response(scene_exist_context)
            if "yes" in scene_exist_ans.lower():
                scene_existence_score += 1
                
                scene_exist_context.append({
                    "role": "assistant",
                    "content": [{"type": "text", "text": "Yes"}] 
                })
                # Three facets are evaluated by default; character is dropped if no characters exist.
                valid_facets = 3
                # character related questions
                ch_attr_score = 0
                ch_action_score = 0
                character_score = 0
                character_action_questions = scene_question["character_action"]
                if len(character_action_questions) > 0:
                    for character_name, character_action_question in character_action_questions.items():
                        attr_score = 0
                        anchor_qs = character_anchor_questions[character_name]
                        locate_flag = False
                        character_anchor_context = scene_exist_context[:]
                        # Ask locate questions until the character is found; then judge remaining attributes.
                        # for attr_type, attr_qs in anchor_qs.items():
                        for attr_qs in anchor_qs.values():
                            locate_question = attr_qs["locate_question"]
                            if not locate_flag:
                                character_anchor_context.append({"role": "user", "content": [{"type": "text", "text": locate_question + CONTROL_SUFFIX}]})
                                anchor_ans = self.get_mllm_response(character_anchor_context)
                                if "yes" in anchor_ans.lower():
                                    character_anchor_context.append({"role": "assistant", "content": [{"type": "text", "text": "Yes"}]})
                                    locate_flag = True
                                    attr_score += 1
                                else:
                                    character_anchor_context.append({"role": "assistant", "content": [{"type": "text", "text": "No"}]})
                            else:
                                judge_question = attr_qs["judge_question"]
                                character_anchor_context.append({"role": "user", "content": [{"type": "text", "text": judge_question + CONTROL_SUFFIX}]})
                                judge_ans = self.get_mllm_response(character_anchor_context)
                                if "yes" in judge_ans.lower():
                                    character_anchor_context.append({"role": "assistant", "content": [{"type": "text", "text": "Yes"}]})
                                    attr_score += 1
                                else:
                                    character_anchor_context.append({"role": "assistant", "content": [{"type": "text", "text": "No"}]})

                        # Only check actions if at least one appearance anchor matched.
                        action_score = 0
                        if attr_score > 0:
                            for action_q in character_action_question:
                                character_action_context = character_anchor_context + [{"role": "user", "content": [{"type": "text", "text": action_q + CONTROL_SUFFIX}]}]
                                action_ans = self.get_mllm_response(character_action_context)
                                if "yes" in action_ans.lower():
                                    action_score += 1

                        attr_score /= len(anchor_qs)
                        action_score /= len(character_action_question)
                        
                        ch_attr_score += attr_score
                        ch_action_score += action_score
                        character_score += (attr_score + action_score) / 2

                    ch_attr_score /= len(character_action_questions)
                    ch_action_score /= len(character_action_questions)
                    character_score /= len(character_action_questions)
                else:
                    valid_facets -= 1

                character_attr_score += ch_attr_score
                character_action_score += ch_action_score
                
                # background related questions
                background_score = 0
                bg_type_q = scene_question["background_type"]
                bg_conformity_qs = scene_question["background_conformity"]
                bg_type_context = scene_exist_context + [{"role": "user", "content": [{"type": "text", "text": bg_type_q + CONTROL_SUFFIX}]}]
                bg_type_ans = self.get_mllm_response(bg_type_context)
                bg_type_score = 0
                if "yes" in bg_type_ans.lower():
                    bg_type_score += 1

                bg_conformity_score = 0
                for bg_conformity_q in bg_conformity_qs:
                    bg_conformity_context = scene_exist_context + [{"role": "user", "content": [{"type": "text", "text": bg_conformity_q + CONTROL_SUFFIX}]}]
                    bg_conformity_ans = self.get_mllm_response(bg_conformity_context)
                    if "yes" in bg_conformity_ans.lower():
                        bg_conformity_score += 1

                bg_conformity_score /= len(bg_conformity_qs)
                background_score = (bg_type_score + bg_conformity_score) / 2
                
                background_type_score += bg_type_score
                background_conformity_score += bg_conformity_score
                # camera movement related questions
                cm_score = 0
                camera_movement_q = scene_question["camera_movement"]
                camera_movement_context = scene_exist_context + [{"role": "user", "content": [{"type": "text", "text": camera_movement_q + CONTROL_SUFFIX}]}]
                camera_movement_ans = self.get_mllm_response(camera_movement_context)
                if "yes" in camera_movement_ans.lower():
                    cm_score += 1
                    
                camera_movement_score += cm_score

                # Aggregate the available facet scores for this scene.
                scene_score += (character_score + background_score + cm_score) / valid_facets
            else:
                continue


        # Normalize accumulated scores by the number of scenes.
        scene_score /= len(fga_questions["scene_questions"])
        scene_existence_score /= len(fga_questions["scene_questions"])
        character_attr_score /= len(fga_questions["scene_questions"])
        character_action_score /= len(fga_questions["scene_questions"])
        background_type_score /= len(fga_questions["scene_questions"])
        background_conformity_score /= len(fga_questions["scene_questions"])
        camera_movement_score /= len(fga_questions["scene_questions"])
        
        score_dict = {
            "sample_score": scene_score,
            "scene_existence_score": scene_existence_score,
            "character_attr_score": character_attr_score,
            "character_action_score": character_action_score,
            "background_type_score": background_type_score,
            "background_conformity_score": background_conformity_score,
            "camera_movement_score": camera_movement_score
        }
        # return scene_score
        return score_dict
    
    def get_mllm_response(self, messages: List[dict], max_new_tokens: int=128):
        inputs = self.mllm_processor.apply_chat_template(
            messages,
            tokenize=True,
            add_generation_prompt=True,
            return_dict=True,
            return_tensors="pt"
        )
        inputs = inputs.to(self.mllm.device)
        # Inference: Generation of the output
        generated_ids = self.mllm.generate(**inputs, max_new_tokens=max_new_tokens)
        generated_ids_trimmed = [
            out_ids[len(in_ids) :] for in_ids, out_ids in zip(inputs.input_ids, generated_ids)
        ]
        output_text = self.mllm_processor.batch_decode(
            generated_ids_trimmed, skip_special_tokens=True, clean_up_tokenization_spaces=False
        )[0]
        return output_text

    def load_mllm(self, model_name_or_path: str):
        # Load the MLLM with bfloat16 and flash-attention for efficient inference.
        self.mllm = Qwen3VLForConditionalGeneration.from_pretrained(
            model_name_or_path,
            dtype=torch.bfloat16,
            attn_implementation="flash_attention_2",
            device_map="auto",
        )
        self.mllm_processor = AutoProcessor.from_pretrained(model_name_or_path)


def get_args():
    parser = argparse.ArgumentParser(description="Fine-grained alignment evaluation launched.")
    parser.add_argument("--mllm_path", type=str, default=f"{ROOT_ABS_PATH}/ckpts/Qwen3-VL-8B-Instruct", help="Path to the multimodal LLM for QA.")
    parser.add_argument("--src_path", type=str, default=f"{ROOT_ABS_PATH}/data/prompt.json", help="Path to source the prompt metadata.")
    parser.add_argument("--eval_data", type=str, required=True, help="Path to the list file of videos to be evaluated.")
    parser.add_argument("--result_path", type=str, default=f"{ROOT_ABS_PATH}/results/fine_grained_alignment_results.json", help="Path to save the evaluation results.")
    args = parser.parse_args()
    return args


def main(args):
    assert os.path.exists(args.eval_data), f"Failed to find corresponding file of {args.eval_data}, please carefully check your path again!"
    results = {
        "overall_score": 0.0,
        "overall_scene_existence_score": 0.0,
        "overall_character_attr_score": 0.0,
        "overall_character_action_score": 0.0,
        "overall_background_type_score": 0.0,
        "overall_background_conformity_score": 0.0,
        "overall_camera_movement_score": 0.0,
        "sample_scores": {}
    }
    total_score = 0.0
    total_scene_existence_score = 0.0
    total_character_attr_score = 0.0
    total_character_action_score = 0.0
    total_background_type_score = 0.0
    total_background_conformity_score = 0.0
    total_camera_movement_score = 0.0
    
    fga_scorer = FgaScorer(mllm_path=args.mllm_path)
    # eval_data: {test_id: video_path}; src_path: {theme: {sample_id: metadata with fga_questions}}.
    with open(args.eval_data, 'r') as f1, open(args.result_path, 'w') as f2, open(args.src_path, 'r') as f3:
        test_samples = json.load(f1)
        prompt_data = json.load(f3)
        for test_id, video_path in tqdm(test_samples.items()):
            # Derive theme name by stripping the trailing numeric suffix from test_id.
            theme_name = "_".join(test_id.split('_')[:-1])
            # Load the pre-generated fine-grained QA questions for this sample.
            fga_questions = prompt_data[theme_name][test_id]["fga_questions"]
            try:
                sample_score = fga_scorer.get_fga_score(video_path, fga_questions)
                results["sample_scores"][test_id] = sample_score
                total_score += sample_score["sample_score"]
                total_scene_existence_score += sample_score["scene_existence_score"]
                total_character_attr_score += sample_score["character_attr_score"]
                total_character_action_score += sample_score["character_action_score"]
                total_background_type_score += sample_score["background_type_score"]
                total_background_conformity_score += sample_score["background_conformity_score"]
                total_camera_movement_score += sample_score["camera_movement_score"]
            except Exception as e:
                print(f"{str(e)} encountered when processing {video_path}! Ignoring this video...")
                traceback.print_exc()
                results["sample_scores"][test_id] = {}
        total_score = round(total_score / len(test_samples), 4)
        total_scene_existence_score = round(total_scene_existence_score / len(test_samples), 4)
        total_character_attr_score = round(total_character_attr_score / len(test_samples), 4)
        total_character_action_score = round(total_character_action_score / len(test_samples), 4)
        total_background_type_score = round(total_background_type_score / len(test_samples), 4)
        total_background_conformity_score = round(total_background_conformity_score / len(test_samples), 4)
        total_camera_movement_score = round(total_camera_movement_score / len(test_samples), 4)
        
        results["overall_score"] = total_score
        results["overall_scene_existence_score"] = total_scene_existence_score
        results["overall_character_attr_score"] = total_character_attr_score
        results["overall_character_action_score"] = total_character_action_score
        results["overall_background_type_score"] = total_background_type_score
        results["overall_background_conformity_score"] = total_background_conformity_score
        results["overall_camera_movement_score"] = total_camera_movement_score
        
        # Write per-sample and overall scores to the output file.
        json.dump(results, f2, indent=4, ensure_ascii=False)   
        print(f"Average fine-grained alignment score is: {total_score: .4f}")


if __name__ == "__main__":
    args = get_args()
    main(args)